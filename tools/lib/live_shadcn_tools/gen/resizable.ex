defmodule LiveShadcnTools.Gen.Resizable do
  @moduledoc """
  The pointer-resizable panel recipe.

  ## `aria-orientation` belongs to the handle, and to nothing else

  The handle is a `role="separator"`, which is a widget when it is focusable —
  so `aria-orientation` and the `aria-value*` set are all allowed on it, and
  react-resizable-panels puts them there.

  The panel group is a bare `<div>`. `aria-orientation` on an element with no
  role that takes it is what axe reports as `aria-allowed-attr`, and it was
  reported here: the recipe put the attribute on the group as well. React puts
  nothing of the sort there — checked against the rendered reference, whose
  group carries only `data-slot`, `class`, `data-group` and a style.

  It is `data-orientation` now. That is an attribute any element may carry, and
  it keeps the value available to a caller who wants to select on it.

  **Upstream reads an attribute upstream does not set.** shadcn styles the group
  with `aria-[orientation=vertical]:flex-col`, and nothing in
  react-resizable-panels ever writes `aria-orientation` there — so a vertical
  panel group does not become a column in React either. Matching that is what
  parity means, and the class string is upstream's to fix.
  """

  alias LiveShadcnTools.Gen.Heex

  @doc "The module source for a resizable panel group."
  def module(spec, opts) do
    handle = part!(spec, "resizable_handle")
    group = part!(spec, "resizable_panel_group")
    icon = handle["tree"] |> Map.fetch!("children") |> hd() |> Map.fetch!("children") |> hd()

    group_class =
      insert_before(
        group["tree"]["class"],
        "aria-[orientation=vertical]:flex-col",
        "overflow-hidden"
      )

    """
    defmodule #{inspect(Keyword.fetch!(opts, :module))} do
    #{moduledoc(spec)}

      use Phoenix.Component

      alias LiveBase.Resizable

      @doc "The `resizable-handle` part."
      attr :with_handle, :string, default: nil
      attr :class, :any, default: nil, doc: "Appended to the class string upstream renders."
      attr :rest, :global, include: ["data-slot"]
      slot :inner_block
      attr :orientation, :string, default: "vertical", values: ["horizontal", "vertical"]

      def resizable_handle(assigns) do
        ~H\"\"\"
        <div
          data-slot={@rest[:"data-slot"] || "resizable-handle"}
          data-lb-resizable-handle
          role="separator"
          tabindex="0"
          aria-orientation={@orientation}
          aria-valuemin="0"
          aria-valuemax="100"
          aria-valuenow="50"
          class={[#{inspect(handle["tree"]["class"])}, @class]}
          {Map.drop(@rest, [:"data-slot"])}
        >
          <div :if={@with_handle} class=#{inspect(icon["class"])} />
          {render_slot(@inner_block)}
        </div>
        \"\"\"
      end

      @doc "The `resizable-panel` part."
      attr :class, :any, default: nil, doc: "Appended to the class string upstream renders."
      attr :rest, :global, include: ["data-slot"]
      slot :inner_block

      def resizable_panel(assigns) do
        ~H\"\"\"
        <div
          data-slot={@rest[:"data-slot"] || "resizable-panel"}
          class={["flex flex-1", @class]}
          style="border-color: currentColor"
          {Map.drop(@rest, [:"data-slot"])}
        >
          {render_slot(@inner_block)}
        </div>
        \"\"\"
      end

      @doc "The `resizable-panel-group` part."
      attr :class, :any, default: nil, doc: "Appended to the class string upstream renders."
      attr :rest, :global, include: ["data-slot"]
      slot :inner_block
      attr :id, :string, required: true
      attr :orientation, :string, default: "horizontal", values: ["horizontal", "vertical"]

      def resizable_panel_group(assigns) do
        ~H\"\"\"
        <div
          data-slot={@rest[:"data-slot"] || "resizable-panel-group"}
          id={@id}
          phx-hook={Resizable.hook()}
          data-orientation={@orientation}
          class={[#{inspect(group_class)}, @class]}
          {Map.drop(@rest, [:"data-slot"])}
        >
          {render_slot(@inner_block)}
        </div>
        \"\"\"
      end
    end
    """
  end

  defp part!(spec, name), do: Enum.find(spec["parts"], &(&1["name"] == name))

  defp insert_before(classes, before, class) do
    classes
    |> String.split()
    |> List.insert_at(Enum.find_index(String.split(classes), &(&1 == before)), class)
    |> Enum.join(" ")
  end

  defp moduledoc(spec) do
    """
      @moduledoc \"\"\"
      #{Heex.headline(spec)}

      Generated by `mix ui.gen` from `#{Heex.spec_ref(spec)}`. Every
      class string and every `data-slot` below came from upstream. Change the
      spec or the recipe, not this file.
      \"\"\"\\
    """
  end
end
