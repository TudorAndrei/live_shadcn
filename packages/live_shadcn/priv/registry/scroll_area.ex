defmodule LiveShadcn.UI.ScrollArea do
  @moduledoc """
  Scroll area. Groups all parts of the scroll area.

  Generated by `mix ui.gen` from `registry/spec/shadcn/scroll-area.json`. Every
  class string, every `data-slot`, and every data attribute below came from
  upstream. Change the spec or the recipe, not this file.
  """

  use Phoenix.Component

  # live-shadcn: upstream facts start
  @upstream_facts %{
    "jsx/ScrollArea/class/0" => "cn-scroll-area relative",
    "jsx/ScrollArea/class/1" =>
      "cn-scroll-area-viewport size-full rounded-[inherit] transition-[color,box-shadow] outline-none focus-visible:ring-[3px] focus-visible:ring-ring/50 focus-visible:outline-1",
    "jsx/ScrollBar/class/0" =>
      "cn-scroll-area-scrollbar flex touch-none p-px transition-colors select-none",
    "jsx/ScrollBar/class/1" => "cn-scroll-area-thumb relative flex-1 bg-border"
  }
  # live-shadcn: upstream facts end
  Module.get_attribute(__MODULE__, :upstream_facts)

  defp upstream_fact(key), do: Map.fetch!(@upstream_facts, key)

  alias LiveBase.Scroller

  @doc """
  Groups all parts of the scroll area.

      <.scroll_area id="log" class="h-72">
        <p :for={line <- @lines}>{line}</p>
      </.scroll_area>

  The scrollbar is drawn rather than the platform's, so a style sheet can
  reach it. Everything that takes is a measurement — how much there is to
  scroll, how far down the reader is, how tall the thumb should be — and
  every one of them is made in the browser. The server is told none of it.
  """

  attr(:id, :string, required: true, doc: "The hook needs one to be found by.")

  attr(:orientation, :string,
    default: "vertical",
    values: ["vertical", "horizontal"],
    doc: "Which way the scrollbar runs."
  )

  attr(:class, :any, default: nil, doc: "Appended to the class string upstream renders.")
  attr(:rest, :global)
  slot(:inner_block, required: true, doc: "What scrolls.")

  def scroll_area(assigns) do
    ~H"""
    <div
      data-slot={@rest[:"data-slot"] || "scroll-area"}
      id={@id}
      phx-hook={Scroller.hook()}
      phx-mounted={Scroller.owned_attributes()}
      class={[upstream_fact("jsx/ScrollArea/class/0"), (@class || "")]}
      {Map.drop(@rest, [:"data-slot"])}
    >
      <div
        data-slot="scroll-area-viewport"
        data-lb-scroller
        tabindex="0"
        style="overflow: scroll; scrollbar-width: none"
        class={upstream_fact("jsx/ScrollArea/class/1")}
      >
        {render_slot(@inner_block)}
      </div>
      <div
        data-slot="scroll-area-scrollbar"
        data-orientation={@orientation}
        style={
          if(@orientation == "horizontal",
            do: "position: absolute; inset-inline: 0; inset-block-end: 0",
            else: "position: absolute; inset-block: 0; inset-inline-end: 0"
          )
        }
        class={upstream_fact("jsx/ScrollBar/class/0")}
      >
        <div
          data-slot="scroll-area-thumb"
          data-lb-thumb
          data-orientation={@orientation}
          style={
            if(@orientation == "horizontal",
              do: "flex: none; width: var(--scroll-area-thumb-width); height: 100%",
              else: "flex: none; width: 100%; height: var(--scroll-area-thumb-height)"
            )
          }
          class={upstream_fact("jsx/ScrollBar/class/1")}
        />
      </div>
      <div />
    </div>
    """
  end
end