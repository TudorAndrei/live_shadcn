defmodule LiveShadcn.UI.Combobox do
  @moduledoc """
  Combobox. Groups all parts of the combobox.

  Generated by `mix ui.gen` from `registry/spec/shadcn/combobox.json`. Every
  class string, every `data-slot`, and every data attribute below came from
  upstream. Change the spec or the recipe, not this file.
  """

  use Phoenix.Component

  alias LiveBase.FormControl
  alias LiveBase.Listbox
  alias LiveBase.Popover

  @doc """
  Groups all parts of the combobox.

      <.combobox id="style" field={@form[:style]}>
        <:option value="vega" label="Vega" />
        <:option value="nova" label="Nova" />
      </.combobox>

  The trigger is a button, and a button submits nothing, so there is a hidden
  input beside it carrying the chosen value. Choosing runs on the client and
  fires `change`, so `phx-change` still sees it.
  """
  attr(:id, :string, required: true, doc: "Every id inside the listbox derives from it.")

  attr(:field, Phoenix.HTML.FormField,
    default: nil,
    doc: "A form field. Fills in id, name, value and errors."
  )

  attr(:name, :string, default: nil)
  attr(:value, :any, default: nil, doc: "The chosen value.")

  attr(:placeholder, :string,
    default: "Select…",
    doc: "What the trigger reads with nothing chosen."
  )

  attr(:labelledby, :string, default: nil, doc: "The id of the label that names it.")
  attr(:errors, :list, default: [])
  attr(:open, :boolean, default: false)
  attr(:disabled, :boolean, default: false)
  attr(:readonly, :boolean, default: false)
  attr(:required, :boolean, default: false)
  attr(:side, :string, default: "bottom", values: ["top", "right", "bottom", "left"])
  attr(:align, :string, default: "start", values: ["start", "center", "end"])
  attr(:offset, :integer, default: 4)
  attr(:class, :any, default: nil, doc: "Appended to the list's class string.")
  attr(:label_class, :any, default: nil)
  attr(:list_class, :any, default: nil)
  attr(:item_class, :any, default: nil)
  attr(:separator_class, :any, default: nil)
  attr(:trigger_class, :any, default: nil)
  attr(:value_class, :any, default: nil)
  attr(:align_offset, :string, default: "0")
  attr(:anchor, :string, default: nil)
  attr(:side_offset, :string, default: "6")
  attr(:rest, :global)

  slot :option, doc: "One value to choose." do
    attr(:value, :string, required: true, doc: "Unique. What the form submits.")
    attr(:label, :string, doc: "What it reads. Defaults to the value.")
    attr(:disabled, :boolean)
  end

  slot(:inner_block, doc: "Anything the options do not cover.")

  def combobox(assigns) do
    assigns = FormControl.from_field(assigns)

    ~H"""
    <div
      id={@id}
      phx-window-keydown={Popover.close(@id)}
      phx-key="Escape"
      phx-click-away={Popover.dismiss(@id)}
      {@rest}
    >
      <button
        data-slot="combobox-trigger"
        id={Popover.trigger_id(@id)}
        type="button"
        role="combobox"
        aria-labelledby={@labelledby}
        aria-haspopup="listbox"
        aria-expanded={to_string(@open)}
        aria-controls={Popover.popup_id(@id)}
        phx-click={if(not @disabled, do: Popover.toggle(@id))}
        phx-mounted={Popover.owned_attributes(:trigger)}
        data-popup-open={flag(@open)}
        data-list-empty={flag(@option == [])}
        data-pressed={flag(@open)}
        data-disabled={flag(@disabled)}
        data-readonly={flag(@readonly)}
        data-required={flag(@required)}
        data-valid={flag(@errors == [])}
        data-invalid={flag(@errors != [])}
        data-filled={flag(@value not in [nil, ""])}
        data-placeholder={flag(@value in [nil, ""])}
        class={["cn-combobox-trigger", ["block w-full", @trigger_class]]}
      >
        {label(@option, @value) || @placeholder}<LiveShadcn.Icon.icon
          name="chevron-down"
          class="cn-combobox-trigger-icon pointer-events-none"
        />
      </button>
      <input
        type="hidden"
        id={Listbox.input_id(@id)}
        name={@name}
        value={@value}
        disabled={@disabled}
        required={@required}
        phx-mounted={Listbox.owned_attributes(:input)}
      />
      <div>
        <div
          id={Popover.positioner_id(@id)}
          hidden={not @open}
          phx-hook={Popover.hook()}
          data-lb-anchor={Popover.trigger_id(@id)}
          data-lb-side={@side}
          data-lb-align={@align}
          data-lb-offset={to_string(@offset)}
          data-lb-autofocus
          phx-mounted={Popover.owned_attributes(:positioner)}
          data-open={flag(@open)}
          data-closed={flag(not @open)}
          data-empty={flag(@option == [])}
          class="isolate z-50"
        >
          <div
            data-slot="combobox-content"
            id={Popover.popup_id(@id)}
            role="listbox"
            tabindex="-1"
            hidden={not @open}
            data-lb-popup
            phx-hook="LiveBase.Roving"
            data-lb-roving="option"
            data-lb-orientation="vertical"
            data-lb-highlight="data-highlighted"
            phx-mounted={Popover.owned_attributes(:popup)}
            data-open={flag(@open)}
            data-closed={flag(not @open)}
            data-empty={flag(@option == [])}
            data-chips={@anchor not in [nil, false, ""]}
            class={[
              "cn-combobox-content cn-combobox-content-logical cn-menu-target cn-menu-translucent group/combobox-content relative max-h-(--available-height) w-(--anchor-width) max-w-(--available-width) min-w-[calc(var(--anchor-width)+--spacing(7))] origin-(--transform-origin) data-[chips=true]:min-w-(--anchor-width)",
              @class
            ]}
            data-lb-style-target
            data-lb-measure
          >
            <div
              :for={option <- @option}
              data-slot="combobox-item"
              id={Listbox.option_id(@id, option[:value])}
              role="option"
              tabindex="-1"
              aria-selected={to_string(option[:value] == @value)}
              data-selected={flag(option[:value] == @value)}
              phx-click={
                if(option[:disabled] != true,
                  do: Listbox.choose(listbox: @id, value: option[:value], label: option[:label])
                )
              }
              phx-mounted={Listbox.owned_attributes(:option)}
              data-disabled={flag(option[:disabled] == true)}
              class={[
                "cn-combobox-item relative flex w-full cursor-default items-center outline-hidden select-none data-disabled:pointer-events-none data-disabled:opacity-50 [&_svg]:pointer-events-none [&_svg]:shrink-0",
                @item_class
              ]}
              data-lb-style-target
            >
              {option[:label] || option[:value]}
              <span class="cn-combobox-item-indicator">
                <LiveShadcn.Icon.icon
                  name="check"
                  class="cn-combobox-item-indicator-icon pointer-events-none"
                />
              </span>
            </div>
          </div>
        </div>
      </div>
    </div>
    """
  end

  # What the trigger reads before anything has been chosen, and after.
  defp label(options, value) do
    case Enum.find(options, &(&1[:value] == value)) do
      nil -> nil
      option -> option[:label] || option[:value]
    end
  end

  defp flag(true), do: ""
  defp flag(_state), do: nil
end
