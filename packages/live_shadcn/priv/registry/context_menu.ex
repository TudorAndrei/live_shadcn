defmodule LiveShadcn.UI.ContextMenu do
  @moduledoc """
  Context menu. A component that creates a context menu activated by right clicking or long pressing.

  Generated by `mix ui.gen` from `registry/spec/shadcn/context-menu.json`. Every
  class string, every `data-slot`, and every data attribute below came from
  upstream. Change the spec or the recipe, not this file.
  """

  use Phoenix.Component

  # live-shadcn: upstream facts start
  @upstream_facts %{
    "jsx/ContextMenuContent/class/0" => "isolate z-50 outline-none",
    "jsx/ContextMenuContent/class/1" => "cn-context-menu-content cn-context-menu-content-logical cn-menu-target cn-menu-translucent z-50 max-h-(--available-height) origin-(--transform-origin) overflow-x-hidden overflow-y-auto outline-none",
    "jsx/ContextMenuItem/class/0" => "cn-context-menu-item group/context-menu-item relative flex cursor-default items-center outline-hidden select-none data-disabled:pointer-events-none data-disabled:opacity-50 [&_svg]:pointer-events-none [&_svg]:shrink-0",
    "jsx/ContextMenuTrigger/class/0" => "cn-context-menu-trigger select-none"
  }
  # live-shadcn: upstream facts end
  Module.get_attribute(__MODULE__, :upstream_facts)

  defp upstream_fact(key), do: Map.fetch!(@upstream_facts, key)

  alias LiveBase.Menu
  alias LiveBase.Popover

  @doc """
  A component that creates a context menu activated by right clicking or long pressing.

      <.context_menu id="actions">
        <:trigger>Actions</:trigger>
        <:item value="regenerate" phx-click="regenerate">Regenerate</:item>
        <:item value="verify" phx-click="verify">Verify</:item>
      </.context_menu>

  The arrow keys walk the items and mark the one they arrive at. Choosing is
  a separate gesture, and only choosing closes the menu.
  """
  attr(:id, :string, required: true, doc: "Every id inside the menu derives from it.")
  attr(:open, :boolean, default: false, doc: "Whether it starts open.")
  attr(:disabled, :boolean, default: false, doc: "Whether the trigger refuses interaction.")
  attr(:side, :string, default: "bottom", values: ["top", "right", "bottom", "left"])
  attr(:align, :string, default: "start", values: ["start", "center", "end"])
  attr(:offset, :integer, default: 4)
  attr(:class, :any, default: nil, doc: "Appended to the menu's class string.")
  attr(:inset, :boolean, default: false, doc: "Line the text up with items that have an icon.")
  attr(:trigger_slot, :string, default: "context-menu-trigger")
  attr(:popup_slot, :string, default: "context-menu-content")
  attr(:item_slot, :string, default: "context-menu-item")

  attr(:item_class, :any, default: nil)
  attr(:label_class, :any, default: nil)
  attr(:separator_class, :any, default: nil)
  attr(:trigger_class, :any, default: nil)
  attr(:align_offset, :string, default: "4")
  attr(:side_offset, :string, default: "0")
  attr(:variant, :string, default: "default", values: ["default", "destructive"])
  attr(:rest, :global)

  slot(:trigger, required: true, doc: "What opens it.")

  slot :item, doc: "One thing to choose. Choosing it closes the menu." do
    attr(:value, :string, required: true, doc: "Unique. The item's id derives from it.")
    attr(:disabled, :boolean, doc: "Whether it refuses to be chosen.")
    attr(:"phx-click", :any, doc: "What choosing it does, beside closing the menu.")
    attr(:"phx-value-value", :any)
    attr(:navigate, :string)
    attr(:patch, :string)
    attr(:href, :string)
  end

  slot(:inner_block, doc: "Anything the items do not cover.")

  def context_menu(assigns) do
    ~H"""
    <div
      id={@id}
      class="contents"
      phx-window-keydown={Popover.close(@id)}
      phx-key="Escape"
      phx-click-away={Popover.dismiss(@id)}
      {@rest}
    >
      <div
        role="button"
        tabindex="0"
        id={Popover.trigger_id(@id)}
        type="button"
        aria-haspopup="menu"
        aria-expanded={to_string(@open)}
        aria-controls={Popover.popup_id(@id)}
        phx-click={if(not @disabled, do: Popover.toggle(@id))}
        phx-mounted={Popover.owned_attributes(:trigger)}
        data-slot={@trigger_slot}
        data-popup-open={flag(@open)}
        data-pressed={flag(@open)}
        class={[upstream_fact("jsx/ContextMenuTrigger/class/0"), (@trigger_class || "")]}
      >
        {render_slot(@trigger)}
      </div>
      <div class={["contents", (@class || "")]}>
        <div
          id={Popover.positioner_id(@id)}
          hidden={not @open}
          phx-hook={Popover.hook()}
          data-lb-anchor={Popover.trigger_id(@id)}
          data-lb-side={@side}
          data-lb-align={@align}
          data-lb-offset={to_string(@offset)}
          data-lb-autofocus
          phx-mounted={Popover.owned_attributes(:positioner)}
          data-open={flag(@open)}
          data-closed={flag(not @open)}
          class={upstream_fact("jsx/ContextMenuContent/class/0")}
        >
          <div
            id={Popover.popup_id(@id)}
            role="menu"
            tabindex="-1"
            hidden={not @open}
            data-lb-popup
            phx-hook={Menu.hook()}
            data-lb-roving="menuitem"
            data-lb-orientation="vertical"
            data-lb-loop
            data-lb-highlight="data-highlighted"
            phx-mounted={Popover.owned_attributes(:popup)}
            data-slot={@popup_slot}
            data-open={flag(@open)}
            data-closed={flag(not @open)}
            data-variant={@variant}
            class={[
              upstream_fact("jsx/ContextMenuContent/class/1"),
              (@class || "")
            ]}
            data-lb-style-target
            data-lb-measure
          >
            <div
              :for={item <- @item}
              id={Menu.item_id(@id, item[:value])}
              role="menuitem"
              tabindex="-1"
              phx-click={if(item[:disabled] != true, do: Menu.choose(@id, item[:"phx-click"]))}
              phx-mounted={Menu.owned_attributes(:item)}
              {Map.take(item, [:"phx-value-value", :navigate, :patch, :href])}
              data-slot={@item_slot}
              data-disabled={flag(item[:disabled] == true)}
              data-variant={@variant}
              data-inset={flag(@inset)}
              class={[
                upstream_fact("jsx/ContextMenuItem/class/0"),
                (@item_class || "")
              ]}
            >
              {render_slot(item)}
            </div>
          </div>
        </div>
      </div>
    </div>
    """
  end

  defp flag(true), do: ""
  defp flag(_state), do: nil
end