defmodule LiveShadcn.UI.Calendar do
  @moduledoc """
  Calendar.

  Generated by `mix ui.gen` from `registry/spec/shadcn/calendar.json`.
  """

  use Phoenix.Component

  @doc "A deterministic month grid. The server owns the dates and selection."
  attr(:month, Date, default: Date.utc_today())
  attr(:selected, Date, default: nil)
  attr(:week_starts_on, :integer, default: 7, values: 1..7)
  attr(:locale, :string, default: "en", values: ["en"])
  attr(:class, :any, default: nil)
  attr(:rest, :global, include: ["aria-label", "data-slot"])

  def calendar(assigns) do
    assigns = assign(assigns, :weeks, month_weeks(assigns.month, assigns.week_starts_on))

    ~H"""
    <section
      data-slot="calendar"
      style="min-width: 157px"
      class={["cn-calendar group/calendar bg-background w-fit rdp-root", @class]}
      {@rest}
    >
      <div class="relative flex h-9 items-center justify-center px-9 text-sm font-medium rdp-month_caption">
        <button
          type="button"
          aria-label="Go to the previous month"
          style="position: absolute; left: 0"
          class="cn-button group/button inline-flex size-(--cell-size) items-center justify-center p-0 rdp-button_previous"
        >‹</button>
        <span class="rdp-caption_label">{Calendar.strftime(@month, "%B %Y")}</span>
        <button
          type="button"
          aria-label="Go to the next month"
          style="position: absolute; right: 0"
          class="cn-button group/button inline-flex size-(--cell-size) items-center justify-center p-0 rdp-button_next"
        >›</button>
      </div>
      <table
        style="margin-bottom: 13px"
        class="w-full border-collapse rdp-month_grid"
        role="grid"
        aria-label={Calendar.strftime(@month, "%B %Y")}
      >
        <thead>
          <tr class="flex rdp-weekdays">
            <th
              :for={day <- weekday_names(@week_starts_on)}
              style="width: 19px"
              class="flex-1 rounded-(--cell-radius) text-[0.8rem] font-normal text-muted-foreground select-none rdp-weekday"
              scope="col"
            >
              {day}
            </th>
          </tr>
        </thead>
        <tbody>
          <tr :for={week <- @weeks} class="mt-2 flex w-full rdp-week">
            <td
              :for={day <- week}
              style="width: 19px"
              class="group/day relative aspect-square h-full w-full rounded-(--cell-radius) p-0 text-center select-none rdp-day"
            >
              <button
                type="button"
                data-day={Date.to_iso8601(day)}
                data-selected={to_string(day == @selected)}
                class={[
                  "cn-calendar-day-button relative isolate z-10 flex aspect-square size-auto w-full items-center justify-center border-0 leading-none font-normal rdp-day_button data-[selected=true]:bg-primary data-[selected=true]:text-primary-foreground",
                  if(day.month != @month.month, do: "text-muted-foreground opacity-50 rdp-outside")
                ]}
              >
                {day.day}
              </button>
            </td>
          </tr>
        </tbody>
      </table>
    </section>
    """
  end

  defp month_weeks(month, week_starts_on) do
    first = %{month | day: 1}
    offset = rem(Date.day_of_week(first) - week_starts_on + 7, 7)
    start = Date.add(first, -offset)
    last = Date.end_of_month(month)
    weeks = div(offset + last.day + 6, 7)
    for week <- 0..(weeks - 1), do: for(day <- 0..6, do: Date.add(start, week * 7 + day))
  end

  defp weekday_names(week_starts_on) do
    first = ~D[2023-01-02]
    start = Date.add(first, rem(week_starts_on - 1, 7))
    for day <- 0..6, do: Calendar.strftime(Date.add(start, day), "%a")
  end
end
