defmodule LiveShadcn.UI.Toggle do
  @moduledoc """
  Toggle. A two-state button that can be on or off.

  Generated by `mix ui.gen` from `registry/spec/shadcn/toggle.json`. Every
  class string, every `data-slot`, and every data attribute below came from
  upstream. Change the spec or the recipe, not this file.
  """

  use Phoenix.Component

  # live-shadcn: upstream facts start
  @upstream_facts %{
    "cva/toggleVariants/base" =>
      "cn-toggle group/toggle inline-flex items-center justify-center whitespace-nowrap outline-none hover:bg-muted focus-visible:ring-[3px] disabled:pointer-events-none disabled:opacity-50 [&_svg]:pointer-events-none [&_svg]:shrink-0",
    "cva/toggleVariants/default/size" => "default",
    "cva/toggleVariants/default/variant" => "default",
    "cva/toggleVariants/variant/size/default" => "cn-toggle-size-default",
    "cva/toggleVariants/variant/size/lg" => "cn-toggle-size-lg",
    "cva/toggleVariants/variant/size/sm" => "cn-toggle-size-sm",
    "cva/toggleVariants/variant/variant/default" => "cn-toggle-variant-default",
    "cva/toggleVariants/variant/variant/outline" => "cn-toggle-variant-outline"
  }
  # live-shadcn: upstream facts end
  Module.get_attribute(__MODULE__, :upstream_facts)

  defp upstream_fact(key), do: Map.fetch!(@upstream_facts, key)

  @variant_classes (for {"cva/" <> path, value} <- @upstream_facts,
                       [table, "variant", group, choice] <- [String.split(path, "/")],
                       reduce: %{} do
    variants ->
      put_in(
        variants,
        [
          Access.key(table, %{}),
          Access.key(group, %{}),
          Access.key(choice, nil)
        ],
        value
      )
  end)

  alias LiveBase.FormControl

  @doc """
  A two-state button that can be on or off.

      <.toggle field={@form[:bold]} />

  The control a reader sees and the input a form submits are two elements,
  as Base UI documents. Flipping one flips the other, on the client, so a
  click costs no round trip and `phx-change` still fires.

  It needs an accessible name, and a `<label for>` cannot give it one: a
  label names a labelable element, and this is not one. Name it directly:

      <.label id="subscribe-label">Send me the pull requests</.label>
      <.checkbox field={@form[:subscribe]} aria-labelledby="subscribe-label" />
  """
  attr(:field, Phoenix.HTML.FormField,
    default: nil,
    doc: "A form field. Fills in id, name, value and errors."
  )

  attr(:id, :string, default: nil)
  attr(:name, :string, default: nil)
  attr(:value, :string, default: "true", doc: "What the form submits when the control is on.")
  attr(:checked, :boolean, default: nil)
  attr(:errors, :list, default: [])
  attr(:disabled, :boolean, default: false)
  attr(:readonly, :boolean, default: false)
  attr(:required, :boolean, default: false)

  attr(:size, :string,
    default: @upstream_facts["cva/toggleVariants/default/size"],
    values: @variant_classes |> get_in(["toggleVariants", "size"]) |> Map.keys() |> Enum.sort()
  )

  attr(:variant, :string,
    default: @upstream_facts["cva/toggleVariants/default/variant"],
    values: @variant_classes |> get_in(["toggleVariants", "variant"]) |> Map.keys() |> Enum.sort()
  )

  attr(:class, :any, default: nil, doc: "Appended to the class string upstream renders.")
  attr(:rest, :global, include: ["data-slot", "type", "value", "name", "formaction", "disabled"])
  slot(:inner_block)

  def toggle(assigns) do
    assigns = FormControl.from_checkable(assigns)

    ~H"""
    <button
      data-slot={@rest[:"data-slot"] || "toggle"}
      id={@id}
      aria-pressed={to_string(@checked)}
      aria-disabled={to_string(@disabled)}
      phx-click={
        if(@disabled or @readonly,
          do: nil,
          else: FormControl.toggle(control: @id, state: :pressed, input: false)
        )
      }
      phx-mounted={FormControl.owned_attributes()}
      data-pressed={flag(@checked)}
      data-disabled={flag(@disabled)}
      class={[
        variant_class("toggleVariants", "size", @size),
        variant_class("toggleVariants", "variant", @variant),
        upstream_fact("cva/toggleVariants/base"),
        @class
      ]}
      {Map.drop(@rest, [:"data-slot"])}
    >
      {render_slot(@inner_block)}
    </button>
    """
  end

  defp flag(true), do: ""
  defp flag(_state), do: nil

  defp variant_class(table, group, value),
    do: get_in(@variant_classes, [table, group, value])
end