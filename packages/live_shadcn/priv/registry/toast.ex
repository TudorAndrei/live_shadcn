defmodule LiveShadcn.UI.Toast do
  @moduledoc """
  Toast. Groups all parts of an individual toast.

  Generated by `mix ui.gen` from `registry/spec/shadcn/toast.json`. Every
  class string, every `data-slot`, and every data attribute below came from
  upstream. Change the spec or the recipe, not this file.
  """

  use Phoenix.Component

  alias LiveBase.Toast
  alias Phoenix.LiveView.JS

  @doc """
  A stack of messages the reader did not ask for.

      <.toaster id="toasts" dismiss="dismiss_toast">
        <:toast :for={t <- @toasts} id={t.id} type={t.type} title={t.title}>
          {t.description}
        </:toast>
      </.toaster>

  The list is yours. React's toast is a manager the client holds; a
  LiveView already has somewhere to keep a list, and one the client held
  would disagree with the server's the moment it re-rendered — the reader
  would watch a dismissed message come back.

  So closing one is an event, and so is timing out:

      def handle_event("dismiss_toast", %{"id" => id}, socket) do
        {:noreply, update(socket, :toasts, &Enum.reject(&1, fn t -> t.id == id end))}
      end

  How the stack is placed — how tall each toast turned out, how far back it
  sits, how far a finger has pushed it — is measured in the browser, which
  is the only place any of it is known.
  """

  attr(:id, :string, required: true, doc: "The hook needs one, and each toast derives its own.")

  attr(:dismiss, :string,
    required: true,
    doc: "The event pushed when a toast is closed or times out. Its payload is `%{id: id}`."
  )

  attr(:duration, :integer,
    default: 5000,
    doc: "How long a toast stays, in milliseconds. Zero to leave it until it is closed."
  )

  attr(:label, :string, default: "Notifications", doc: "Names the region to a screen reader.")
  attr(:class, :any, default: nil, doc: "Appended to the class string upstream renders.")
  attr(:rest, :global)

  slot :toast, doc: "One message. The slot's content is its description." do
    attr(:id, :string, required: true, doc: "What comes back with the dismiss event.")
    attr(:title, :string)
    attr(:type, :string, doc: "`success`, `info`, `warning` or `error`.")
  end

  def toaster(assigns) do
    ~H"""
    <div
      data-slot={@rest[:"data-slot"] || "toast-viewport"}
      id={@id}
      phx-hook={Toast.hook()}
      data-lb-toasts
      data-lb-dismiss={@dismiss}
      data-lb-duration={@duration}
      role="region"
      aria-label={@label}
      class={[
        "pointer-events-none fixed inset-x-4 bottom-4 z-50 mx-auto w-auto max-w-sm outline-none sm:right-4 sm:left-auto sm:mx-0 sm:w-full",
        @class
      ]}
      {Map.drop(@rest, [:"data-slot"])}
    >
      <div
        :for={toast <- @toast}
        data-slot="toast"
        id={Toast.toast_id(@id, toast[:id])}
        data-type={toast[:type]}
        role="status"
        aria-live="polite"
        class="cn-toast group/toast pointer-events-auto absolute right-0 bottom-0 z-[calc(1000-var(--toast-index))] w-full origin-bottom border bg-popover text-popover-foreground shadow-lg will-change-transform outline-none select-none focus-visible:border-ring focus-visible:ring-[3px] focus-visible:ring-ring/50 [--gap:0.75rem] [--height:var(--toast-frontmost-height,var(--toast-height))] [--offset-y:calc(var(--toast-offset-y)*-1+calc(var(--toast-index)*var(--gap)*-1)+var(--toast-swipe-movement-y))] [--peek:0.75rem] [--scale:calc(max(0,1-(var(--toast-index)*0.1)))] [--shrink:calc(1-var(--scale))] h-(--height) [transform:translateX(var(--toast-swipe-movement-x))_translateY(calc(var(--toast-swipe-movement-y)-(var(--toast-index)*var(--peek))-(var(--shrink)*var(--height))))_scale(var(--scale))] [transition:transform_500ms_cubic-bezier(0.22,1,0.36,1),opacity_500ms,height_150ms] after:absolute after:top-full after:left-0 after:h-[calc(var(--gap)+1px)] after:w-full after:content-[''] data-expanded:h-(--toast-height) data-expanded:[transform:translateX(var(--toast-swipe-movement-x))_translateY(var(--offset-y))] data-limited:opacity-0 data-starting-style:[transform:translateY(150%)] [&[data-ending-style]:not([data-limited]):not([data-swipe-direction])]:[transform:translateY(150%)] data-ending-style:data-[swipe-direction=down]:[transform:translateY(calc(var(--toast-swipe-movement-y)+150%))] data-ending-style:data-[swipe-direction=left]:[transform:translateX(calc(var(--toast-swipe-movement-x)-150%))_translateY(var(--offset-y))] data-ending-style:data-[swipe-direction=right]:[transform:translateX(calc(var(--toast-swipe-movement-x)+150%))_translateY(var(--offset-y))] data-ending-style:data-[swipe-direction=up]:[transform:translateY(calc(var(--toast-swipe-movement-y)-150%))] data-expanded:data-ending-style:data-[swipe-direction=down]:[transform:translateY(calc(var(--toast-swipe-movement-y)+150%))] data-expanded:data-ending-style:data-[swipe-direction=left]:[transform:translateX(calc(var(--toast-swipe-movement-x)-150%))_translateY(var(--offset-y))] data-expanded:data-ending-style:data-[swipe-direction=right]:[transform:translateX(calc(var(--toast-swipe-movement-x)+150%))_translateY(var(--offset-y))] data-expanded:data-ending-style:data-[swipe-direction=up]:[transform:translateY(calc(var(--toast-swipe-movement-y)-150%))]"
        data-lb-style-target
        data-lb-measure
      >
        <div
          data-slot="toast-content"
          class="flex h-full items-center gap-3 overflow-hidden p-4 transition-opacity duration-250 ease-[cubic-bezier(0.22,1,0.36,1)] data-behind:opacity-0 data-expanded:opacity-100"
          data-lb-style-target
        >
          <h2
            :if={toast[:title]}
            data-slot="toast-title"
            data-type={toast[:type]}
            class="text-sm font-medium"
          >
            {toast[:title]}
          </h2>
          <p
            data-slot="toast-description"
            data-type={toast[:type]}
            class="text-sm text-muted-foreground"
          >
            {render_slot(toast)}
          </p>
          <button
            data-slot="toast-close"
            type="button"
            phx-click={JS.push(@dismiss, value: %{id: Toast.toast_id(@id, toast[:id])})}
            data-type={toast[:type]}
            aria-label="Close toast"
            class="relative shrink-0 text-muted-foreground after:absolute after:-inset-2 after:content-[''] hover:text-foreground"
          >
            <LiveShadcn.Icon.icon name="x" />
          </button>
        </div>
      </div>
    </div>
    """
  end
end
