  attr(:rest, :global, include: ["data-slot"])
  slot(:inner_block)

  def commit_file_status(assigns) do
    ~H"""
    <span
      class={[
        "font-medium font-mono text-xs",
        if(@status == "added", do: "text-green-600 dark:text-green-400", else: nil),
