defmodule LiveAiElements.Components.PackageInfo do
  @moduledoc """
  Package info. Built on `shadcn/badge`.

  Generated by `mix ui.gen` from `registry/spec/ai_elements/package-info.json`. Every
  class string and every `data-slot` below came from upstream. Change the
  spec or the recipe, not this file.
  """

  use Phoenix.Component

  @doc "The `package_info_header` part."

  attr(:class, :any, default: nil, doc: "Appended to the class string upstream renders.")
  attr(:rest, :global, include: ["data-slot"])
  slot(:inner_block)

  def package_info_header(assigns) do
    ~H"""
    <div class={["flex items-center justify-between gap-2", @class]} {@rest}>
      {render_slot(@inner_block)}
    </div>
    """
  end

  @doc "The `package_info_name` part."
  attr(:name, :string, default: nil)
  attr(:class, :any, default: nil, doc: "Appended to the class string upstream renders.")
  attr(:rest, :global, include: ["data-slot"])
  slot(:inner_block)

  def package_info_name(assigns) do
    ~H"""
    <div class={["flex items-center gap-2", @class]} {@rest}>
      <LiveShadcn.Icon.icon name="package" class="size-4 text-muted-foreground" />
      <span class="font-medium font-mono text-sm">
        <%= if @inner_block == [] do %>
          {@name}
        <% end %>
        {render_slot(@inner_block)}
      </span>
    </div>
    """
  end

  @doc "The `badge` part."
  attr(:change_type, :string, default: nil)

  attr(:variant, :string,
    default: "secondary",
    values: ["default", "destructive", "ghost", "link", "outline", "secondary"]
  )

  attr(:class, :any, default: nil, doc: "Appended to the class string upstream renders.")
  attr(:rest, :global, include: ["data-slot"])
  slot(:inner_block)

  def package_info_change_type(assigns) do
    ~H"""
    <span
      data-slot={@rest[:"data-slot"] || "badge"}
      data-variant={@variant}
      class={[
        "cn-badge group/badge inline-flex w-fit shrink-0 items-center justify-center overflow-hidden whitespace-nowrap focus-visible:border-ring focus-visible:ring-[3px] focus-visible:ring-ring/50 aria-invalid:border-destructive aria-invalid:ring-destructive/20 dark:aria-invalid:ring-destructive/40 [&>svg]:pointer-events-none gap-1 text-xs capitalize",
        if(@change_type == "added",
          do: "bg-blue-100 text-blue-700 dark:bg-blue-900/30 dark:text-blue-400",
          else: nil
        ),
        if(@change_type == "major",
          do: "bg-red-100 text-red-700 dark:bg-red-900/30 dark:text-red-400",
          else: nil
        ),
        if(@change_type == "minor",
          do: "bg-yellow-100 text-yellow-700 dark:bg-yellow-900/30 dark:text-yellow-400",
          else: nil
        ),
        if(@change_type == "patch",
          do: "bg-green-100 text-green-700 dark:bg-green-900/30 dark:text-green-400",
          else: nil
        ),
        if(@change_type == "removed",
          do: "bg-gray-100 text-gray-700 dark:bg-gray-900/30 dark:text-gray-400",
          else: nil
        ),
        variant_class("badgeVariants", "variant", @variant),
        @class
      ]}
      {Map.drop(@rest, [:"data-slot"])}
    >
      <LiveShadcn.Icon.icon :if={@change_type == "added"} name="plus" class="size-3" />
      <LiveShadcn.Icon.icon :if={@change_type == "major"} name="arrow-right" class="size-3" />
      <LiveShadcn.Icon.icon :if={@change_type == "minor"} name="arrow-right" class="size-3" />
      <LiveShadcn.Icon.icon :if={@change_type == "patch"} name="arrow-right" class="size-3" />
      <LiveShadcn.Icon.icon :if={@change_type == "removed"} name="minus" class="size-3" />
      <%= if @inner_block == [] do %>
        {@change_type}
      <% end %>
      {render_slot(@inner_block)}
    </span>
    """
  end

  @doc "The `package_info_version` part."
  attr(:current_version, :string, default: nil)
  attr(:new_version, :string, default: nil)
  attr(:class, :any, default: nil, doc: "Appended to the class string upstream renders.")
  attr(:rest, :global, include: ["data-slot"])
  slot(:inner_block)

  def package_info_version(assigns) do
    ~H"""
    <div
      class={["mt-2 flex items-center gap-2 font-mono text-muted-foreground text-sm", @class]}
      {@rest}
    >
      <%= if @inner_block == [] do %>
        <span :if={@current_version}>
          {@current_version}
        </span>
        <LiveShadcn.Icon.icon
          :if={@current_version && @new_version}
          name="arrow-right"
          class="size-3"
        />
        <span :if={@new_version} class="font-medium text-foreground">
          {@new_version}
        </span>
      <% end %>
      {render_slot(@inner_block)}
    </div>
    """
  end

  @doc "The `package_info` part."
  attr(:change_type, :string, default: nil)
  attr(:current_version, :string, default: nil)
  attr(:name, :string, default: nil)
  attr(:new_version, :string, default: nil)
  attr(:class, :any, default: nil, doc: "Appended to the class string upstream renders.")
  attr(:rest, :global, include: ["data-slot"])
  slot(:inner_block)

  def package_info(assigns) do
    ~H"""
    <div class={["rounded-lg border bg-background p-4", @class]} {@rest}>
      <%= if @inner_block == [] do %>
        <.package_info_header>
          <.package_info_name name={@name} />
          <.package_info_change_type :if={@change_type} change_type={@change_type} />
        </.package_info_header>
        <.package_info_version
          :if={@current_version || @new_version}
          current_version={@current_version}
          new_version={@new_version}
        />
      <% end %>
      {render_slot(@inner_block)}
    </div>
    """
  end

  @doc "The `package_info_description` part."

  attr(:class, :any, default: nil, doc: "Appended to the class string upstream renders.")
  attr(:rest, :global, include: ["data-slot"])
  slot(:inner_block)

  def package_info_description(assigns) do
    ~H"""
    <p class={["mt-2 text-muted-foreground text-sm", @class]} {@rest}>
      {render_slot(@inner_block)}
    </p>
    """
  end

  @doc "The `package_info_content` part."

  attr(:class, :any, default: nil, doc: "Appended to the class string upstream renders.")
  attr(:rest, :global, include: ["data-slot"])
  slot(:inner_block)

  def package_info_content(assigns) do
    ~H"""
    <div class={["mt-3 border-t pt-3", @class]} {@rest}>
      {render_slot(@inner_block)}
    </div>
    """
  end

  @doc "The `package_info_dependencies` part."

  attr(:class, :any, default: nil, doc: "Appended to the class string upstream renders.")
  attr(:rest, :global, include: ["data-slot"])
  slot(:inner_block)

  def package_info_dependencies(assigns) do
    ~H"""
    <div class={["space-y-2", @class]} {@rest}>
      <span class="font-medium text-muted-foreground text-xs uppercase tracking-wide">
        Dependencies
      </span>
      <div class="space-y-1">
        {render_slot(@inner_block)}
      </div>
    </div>
    """
  end

  @doc "The `package_info_dependency` part."
  attr(:name, :string, default: nil)
  attr(:version, :string, default: nil)
  attr(:class, :any, default: nil, doc: "Appended to the class string upstream renders.")
  attr(:rest, :global, include: ["data-slot"])
  slot(:inner_block)

  def package_info_dependency(assigns) do
    ~H"""
    <div class={["flex items-center justify-between text-sm", @class]} {@rest}>
      <%= if @inner_block == [] do %>
        <span class="font-mono text-muted-foreground">
          {@name}
        </span>
        <span :if={@version} class="font-mono text-xs">
          {@version}
        </span>
      <% end %>
      {render_slot(@inner_block)}
    </div>
    """
  end

  # The variant tables, from the `cva` calls upstream writes them in.
  @variants %{
    "badgeVariants" => %{
      "variant" => %{
        "default" => "cn-badge-variant-default",
        "destructive" => "cn-badge-variant-destructive",
        "ghost" => "cn-badge-variant-ghost",
        "link" => "cn-badge-variant-link",
        "outline" => "cn-badge-variant-outline",
        "secondary" => "cn-badge-variant-secondary"
      }
    }
  }

  defp variant_class(table, group, value), do: get_in(@variants, [table, group, value])
end
